const SVG_NS = 'http://www.w3.org/2000/svg';
const _pathCache = {};

// Grid → one SVG path of horizontal runs (fewer nodes than one rect per pixel).
function pathFor(name) {
  if (_pathCache[name]) return _pathCache[name];
  const grid = ICONS[name];
  if (!grid) return '';
  let d = '';
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      const start = x;
      while (x < row.length && row[x] === '#') x++;
      d += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  });
  _pathCache[name] = d;
  return d;
}

export function setIcon(el, name) {
  if (!el) return;
  const host = el.matches('[data-icon]') ? el : el.querySelector('[data-icon]');
  if (!host) return;
  host.dataset.icon = name;
  let svg = host.querySelector('svg');
  if (!svg) {
    svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('viewBox', '0 0 12 12');
    svg.setAttribute('shape-rendering', 'crispEdges');
    svg.setAttribute('aria-hidden', 'true');
    svg.appendChild(document.createElementNS(SVG_NS, 'path'));
    host.appendChild(svg);
  }
  svg.firstChild.setAttribute('d', pathFor(name));
  svg.firstChild.setAttribute('fill', 'currentColor');
}

export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach(el => setIcon(el, el.dataset.icon));
}

export { ICONS };
